import Link from "next/link";
import { notFound } from "next/navigation";
import { db } from "@/lib/db";
import { listCatalogue } from "@/lib/marketplace-data";
import { newId, nowIso } from "@/lib/ids";
import { requireUser } from "@/lib/auth";
import { getInstallerByUserId, getQuoteRequestForInstaller } from "@/lib/data";
import { declineInviteAction } from "@/app/actions/quotes";
import { PageHeader } from "@/components/page-header";
import { createSurveyAction } from "@/app/actions/surveys";
import { STATUS_LABEL, STATUS_TONE, type SurveyStatus } from "@/lib/survey/model";
import { SubmitButton } from "@/components/submit-button";
import { InstallerQuoteForm } from "@/components/installer/installer-quote-form";
import { Alert, ArrowRight, Check, Shield, SunIcon } from "@/components/icons";
import { dateTime, num, peso, shortDate, statusTone, titleCase } from "@/lib/format";
import type { AssessmentResult } from "@/lib/solar/engine";
import type { AssessmentRow, InstallerQuoteRow } from "@/lib/types";

export const metadata = { title: "Lead detail" };

interface LeadSite {
  id: string;
  name: string;
  city: string;
  province: string | null;
  property_type: string;
  ownership: string;
  roof_type: string;
  roof_area_m2: number;
  roof_age_years: number | null;
  daytime_usage: string;
  utility_provider: string | null;
}

export default async function InstallerLeadPage({
  params,
  searchParams,
}: {
  params: Promise<{ id: string }>;
  searchParams: Promise<{ submitted?: string }>;
}) {
  const user = await requireUser(["installer"]);
  const installer = getInstallerByUserId(user.id);
  if (!installer) notFound();

  const { id } = await params;
  const query = await searchParams;
  const request = getQuoteRequestForInstaller(id, installer.id);
  if (!request) notFound();

  const invite = db
    .prepare("SELECT * FROM quote_invites WHERE quote_request_id = ? AND installer_id = ?")
    .get(request.id, installer.id) as { id: string; status: string } | undefined;
  if (!invite) notFound();

  // Idempotent read receipt for the installer's own invite. No customer data changes.
  if (invite.status === "invited") {
    const changed = db.prepare("UPDATE quote_invites SET status = 'viewed' WHERE id = ? AND status = 'invited'").run(invite.id);
    if (changed.changes === 1) {
      // Persisted progress event so the customer's timeline reflects what actually happened.
      db.prepare(
        `INSERT INTO lead_status_events (id, quote_request_id, actor_user_id, actor_role, from_status, to_status, note, created_at)
         VALUES (?, ?, ?, 'installer', ?, ?, ?, ?)`,
      ).run(newId(), request.id, user.id, request.status, request.status, `${installer.business_name} opened your request`, nowIso());
    }
    invite.status = "viewed";
  }

  const site = db
    .prepare(
      `SELECT id, name, city, province, property_type, ownership, roof_type, roof_area_m2,
         roof_age_years, daytime_usage, utility_provider
       FROM sites WHERE id = ?`,
    )
    .get(request.site_id) as LeadSite | undefined;
  const assessment = db
    .prepare("SELECT * FROM assessments WHERE id = ? AND site_id = ?")
    .get(request.assessment_id, request.site_id) as AssessmentRow | undefined;
  if (!site || !assessment) notFound();

  const result = JSON.parse(assessment.result_json) as AssessmentResult;
  const quote = db.prepare("SELECT * FROM installer_quotes WHERE invite_id = ?").get(invite.id) as
    | InstallerQuoteRow
    | undefined;
  const lineItems = quote
    ? (db.prepare("SELECT description, amount_php FROM quote_line_items WHERE quote_id = ?").all(quote.id) as {
        description: string;
        amount_php: number;
      }[])
    : [];

  const events = db
    .prepare("SELECT * FROM lead_status_events WHERE quote_request_id = ? ORDER BY created_at ASC")
    .all(request.id) as { id: string; actor_role: string; from_status: string | null; to_status: string; note: string | null; created_at: string }[];

  const isOpen = request.status === "open" || request.status === "matched";
  const verified = installer.verification_status === "verified";
  const contactShared = request.share_contact === 1;

  return (
    <>
      <PageHeader
        eyebrow={`${site.city}${site.province ? `, ${site.province}` : ""}`}
        title={site.name}
        description={`Customer request created ${shortDate(request.created_at)}. The assessment below was generated by SOLARekta's deterministic model v${assessment.model_version}; it is not your quote.`}
        actions={
          <>
            <span className={`badge badge-${statusTone(request.status)}`}>{request.status}</span>
            <Link href="/installer/leads" className="btn btn-ghost btn-sm">All leads</Link>
          </>
        }
      />

      {query.submitted ? (
        <div className="mb-5 rounded-xl border border-[#bfdcaa] bg-mint px-4 py-3 text-sm text-forest-deep">
          Quote submitted. The customer has been notified and can compare it with other bids.
        </div>
      ) : null}

      {(() => {
        const surveys = db.prepare("SELECT id, reference, status, type FROM site_surveys WHERE quote_request_id = ? AND installer_id = (SELECT id FROM installers WHERE user_id = ?) ORDER BY created_at DESC").all(request.id, user.id) as { id: string; reference: string; status: SurveyStatus; type: string }[];
        return (
          <section className="card card-pad mb-6 flex flex-wrap items-center justify-between gap-3" aria-label="Site survey">
            <div>
              <h2 className="text-lg text-forest-deep">Site survey</h2>
              {surveys.length ? (
                <ul className="mt-1 space-y-1 text-sm">
                  {surveys.map((sv) => <li key={sv.id}><Link href={`/installer/surveys/${sv.id}/review`} className="link-action text-sm">{sv.reference}</Link> <span className={`badge ${STATUS_TONE[sv.status]} ml-1`}>{STATUS_LABEL[sv.status]}</span></li>)}
                </ul>
              ) : <p className="text-sm text-ink-soft">Plan an ocular visit before quoting. Address and utility are filled in from this request.</p>}
            </div>
            <form action={createSurveyAction} className="flex flex-wrap items-end gap-2">
              <input type="hidden" name="quoteRequestId" value={request.id} />
              <input type="hidden" name="type" value={site.property_type === "residential" ? "residential" : "commercial"} />
              <SubmitButton className="btn btn-secondary btn-sm" pendingText="Creating…">{surveys.length ? "Start another survey" : `Start ${site.property_type === "residential" ? "residential" : "commercial"} survey`}</SubmitButton>
            </form>
          </section>
        );
      })()}

      <div className="grid gap-6 lg:grid-cols-[1.5fr_1fr]">
        <div className="space-y-6">
          <section className="card card-pad">
            <div className="flex flex-wrap items-center justify-between gap-2">
              <div>
                <h2 className="text-xl text-forest-deep">Customer assessment snapshot</h2>
                <p className="text-xs text-muted">
                  Model {result.modelVersion} · {titleCase(result.systemType)} · tariff ₱{result.effectiveTariffPhpPerKwh.toFixed(2)}/kWh
                </p>
              </div>
              <span className="badge">{result.location.city}</span>
            </div>

            <div className="mt-4 grid gap-3 sm:grid-cols-3">
              {result.scenarios.map((scenario) => (
                <div
                  key={scenario.name}
                  className={`rounded-xl border p-3 ${scenario.name === "base" ? "border-forest bg-mint/40" : "border-line bg-paper-deep/30"}`}
                >
                  <p className="text-xs font-semibold text-muted">{scenario.label}</p>
                  <p className="mt-1 font-display font-bold tracking-tight text-xl text-forest-deep">{scenario.capacityKwp} kWp</p>
                  <dl className="mt-2 space-y-1 text-xs">
                    <div className="flex justify-between gap-2"><dt className="text-muted">Production</dt><dd className="font-medium text-ink">{num(scenario.annualProductionKwh)} kWh</dd></div>
                    <div className="flex justify-between gap-2"><dt className="text-muted">Est. cost</dt><dd className="font-medium text-ink">{peso(scenario.capexPhp)}</dd></div>
                    <div className="flex justify-between gap-2"><dt className="text-muted">Yr-1 savings</dt><dd className="font-medium text-ink">{peso(scenario.annualSavingsPhp)}</dd></div>
                    <div className="flex justify-between gap-2"><dt className="text-muted">Payback</dt><dd className="font-medium text-ink">{scenario.paybackYears != null ? `${scenario.paybackYears} yrs` : "25y+"}</dd></div>
                  </dl>
                </div>
              ))}
            </div>
            <p className="mt-3 text-xs text-muted">
              The customer&apos;s estimate targets about {Math.round((result.base.params.targetOffset ?? 0.7) * 100)}% of annual
              consumption (capped by roof space) with a {Math.round((1 - result.base.params.shadingFactor) * 100)}% shading allowance. Your quote
              can differ, but explain why.
            </p>

            <div className="mt-5 grid gap-3 border-t border-line pt-4 sm:grid-cols-2">
              <dl className="space-y-2 text-sm">
                {[
                  ["Property type", titleCase(site.property_type)],
                  ["Occupancy", titleCase(site.ownership)],
                  ["Roof material", titleCase(site.roof_type)],
                  ["Roof area", `${site.roof_area_m2} m²`],
                ].map(([label, value]) => (
                  <div key={label} className="flex justify-between gap-3"><dt className="text-muted">{label}</dt><dd className="font-medium text-ink">{value}</dd></div>
                ))}
              </dl>
              <dl className="space-y-2 text-sm">
                {[
                  ["Roof age", site.roof_age_years != null ? `${site.roof_age_years} years` : "—"],
                  ["Daytime usage", titleCase(site.daytime_usage)],
                  ["Utility", site.utility_provider || "—"],
                  ["Annual consumption", `${num(result.annualConsumptionKwh)} kWh`],
                ].map(([label, value]) => (
                  <div key={label} className="flex justify-between gap-3"><dt className="text-muted">{label}</dt><dd className="font-medium text-ink">{value}</dd></div>
                ))}
              </dl>
            </div>
            <p className="mt-3 rounded-lg bg-paper-deep/50 px-3 py-2 text-xs text-muted">
              The customer&apos;s full address and uploaded bill file are never shared with installers through SOLARekta.
            </p>
          </section>

          <section className="card card-pad">
            <h2 className="text-xl text-forest-deep">{quote ? "Your submitted quote" : "Submit your quote"}</h2>
            <p className="mt-1 text-sm text-ink-soft">
              {quote
                ? `Last updated ${dateTime(quote.updated_at)}. You can revise until the customer closes the request.`
                : "Quote the capacity you would actually install and itemise the price. The customer compares bids on the same fields."}
            </p>

            {!verified ? (
              <div className="mt-4 rounded-xl border border-[#f5d68a] bg-sun-soft/60 px-4 py-3 text-sm text-[#6b4708]">
                Your business is not verified, so quoting is disabled.{" "}
                <Link href="/installer/profile" className="font-semibold underline">Check verification status</Link>.
              </div>
            ) : !isOpen ? (
              <div className="mt-4 rounded-xl border border-line bg-paper-deep px-4 py-3 text-sm text-ink-soft">
                This request is closed. Existing quotes remain visible for your records.
              </div>
            ) : (
              <div className="mt-5">
                <InstallerQuoteForm
                  inviteId={invite.id}
                  revise={Boolean(quote)}
                  defaults={{
                    capacityKwp: quote?.capacity_kwp ?? result.base.capacityKwp,
                    expectedAnnualKwh: quote?.expected_annual_kwh ?? result.base.annualProductionKwh,
                    pricePhp: quote?.price_php,
                    warrantyYears: quote?.warranty_years,
                    workmanshipWarrantyYears: quote?.workmanship_warranty_years,
                    timelineWeeks: quote?.timeline_weeks,
                    exclusions: quote?.exclusions ?? undefined,
                    notes: quote?.notes ?? undefined,
                    validUntil: quote?.valid_until ?? undefined,
                    panelModel: quote?.panel_model ?? undefined,
                    inverterModel: quote?.inverter_model ?? undefined,
                    equipmentSupplier: quote?.equipment_supplier ?? undefined,
                    inclusions: quote?.inclusions ?? undefined,
                    panelProductId: quote?.panel_product_id ?? undefined,
                    inverterProductId: quote?.inverter_product_id ?? undefined,
                  }}
                  catalogue={{
                    panels: listCatalogue({ category: "panel" }).map((p) => ({ id: p.id, label: `${p.brand} ${p.model} — ${p.supplier_name}` })),
                    inverters: listCatalogue({ category: "inverter" }).map((p) => ({ id: p.id, label: `${p.brand} ${p.model} — ${p.supplier_name}` })),
                  }}
                  lineItems={lineItems.map((item) => ({ description: item.description, amount: item.amount_php }))}
                />
              </div>
            )}

            {quote && isOpen && verified ? (
              <div className="mt-5 rounded-xl border border-line bg-paper-deep/40 p-4 text-sm">
                <div className="flex flex-wrap items-center justify-between gap-2">
                  <p className="font-semibold text-ink">Current quote: {peso(quote.price_php)}</p>
                  <span className={`badge badge-${statusTone(quote.status)}`}>{quote.status}</span>
                </div>
                <ul className="mt-2 space-y-1 text-xs text-ink-soft">
                  {lineItems.map((item) => (
                    <li key={item.description} className="flex justify-between gap-3">
                      <span>{item.description}</span><span>{peso(item.amount_php)}</span>
                    </li>
                  ))}
                </ul>
              </div>
            ) : null}
          </section>
        </div>

        <aside className="space-y-5">
          <div className="card card-pad">
            <h2 className="text-lg text-forest-deep">Customer request</h2>
            <p className="mt-2 whitespace-pre-line rounded-xl border border-line bg-paper-deep/40 p-3 text-sm text-ink-soft">
              {request.message || "No additional message from the customer."}
            </p>

            <div className="mt-4">
              <p className="text-xs font-semibold text-muted">Contact</p>
              {contactShared ? (
                <ul className="mt-2 space-y-1 text-sm text-ink">
                  <li>{request.contact_name || "Customer"}</li>
                  {request.contact_phone ? <li>{request.contact_phone}</li> : null}
                  {request.contact_email ? <li>{request.contact_email}</li> : null}
                  <li className="text-xs text-muted">Shared with your business by consent for this request only.</li>
                </ul>
              ) : (
                <p className="mt-2 text-sm text-ink-soft">
                  The customer has not shared contact details yet. Keep communication inside the platform and do not
                  attempt to identify them from the site description.
                </p>
              )}
            </div>

            <div className="mt-4 flex flex-wrap items-center gap-2 border-t border-line pt-4">
              <span className={`badge badge-${statusTone(invite.status)}`}>Lead {invite.status}</span>
              {invite.status === "invited" || invite.status === "viewed" ? (
                <form action={declineInviteAction}>
                  <input type="hidden" name="inviteId" value={invite.id} />
                  <button type="submit" className="link-action link-danger text-xs underline">
                    Decline this lead
                  </button>
                </form>
              ) : null}
            </div>
          </div>

          <div className="card card-pad">
            <h2 className="text-lg text-forest-deep">Request timeline</h2>
            <ol className="mt-3 space-y-3">
              {events.map((event) => (
                <li key={event.id} className="border-l-2 border-line pl-3 text-xs">
                  <p className="font-semibold text-ink">{titleCase(event.to_status)}</p>
                  <p className="text-muted">{dateTime(event.created_at)} · {event.actor_role}</p>
                  {event.note ? <p className="mt-0.5 text-ink-soft">{event.note}</p> : null}
                </li>
              ))}
            </ol>
          </div>

          <div className="rounded-2xl bg-forest p-5 text-[#ffffff]">
            <SunIcon className="h-5 w-5 text-sun" />
            <p className="mt-2 text-sm font-semibold">No invented numbers.</p>
            <p className="mt-1 text-xs leading-relaxed text-[#d6ead0]">
              Use your own engineering estimate and equipment data. If your production or price differs materially from the
              model, say why in the notes.
            </p>
          </div>

          <div className="rounded-2xl border border-line bg-[#ffffff] p-4 text-xs leading-relaxed text-ink-soft">
            <p className="flex gap-2"><Shield className="mt-0.5 h-4 w-4 shrink-0 text-forest" /> Quotes are moderated. Inaccurate, misleading or off-platform contact attempts can be withdrawn by an admin.</p>
            <p className="mt-2 flex gap-2"><Check className="mt-0.5 h-4 w-4 shrink-0 text-leaf" /> Ask the customer for a site survey before confirming structural or electrical suitability.</p>
          </div>

          <Link href={`/installer/leads?status=all`} className="link-action text-xs">
            Back to all leads <ArrowRight className="h-3 w-3" />
          </Link>
        </aside>
      </div>
    </>
  );
}
